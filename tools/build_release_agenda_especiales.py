#!/usr/bin/env python3
"""Prepare rollback-friendly, versioned assets and one index switch.

Inputs are the live-derived files generated by patch_live_agenda_especiales.py.
No live files are overwritten during asset staging.
"""
from pathlib import Path
import argparse
import re
import shutil
import hashlib

RELEASE = {
    "graph.js": "graph-agenda-especiales-20261126-v2.js",
    "app.js": "app-agenda-especiales-20261126-v2.js",
    "dashboard-daily-calendar.js": "dashboard-daily-calendar-agenda-especiales-20261126-v2.js",
    "dashboard-daily-calendar.css": "dashboard-daily-calendar-agenda-especiales-20261126-v2.css",
}
VERSION = "20261126-especiales-v2"

def build(src: Path, dest: Path):
    if dest.exists() and any(dest.iterdir()):
        raise RuntimeError("Release folder not empty")
    dest.mkdir(parents=True, exist_ok=True)

    index = (src / "index.php").read_text(encoding="utf-8")
    for original, renamed in RELEASE.items():
        text = (src / original).read_text(encoding="utf-8")
        if len(text) < 8000:
            raise RuntimeError(f"{original}: unexpected short asset")
        shutil.copyfile(src / original, dest / renamed)
        pattern = re.compile(
            r'((?:src|href)\s*=\s*["\'])' + re.escape(original) + r'\?v=[^"\']+(["\'])',
            flags=re.IGNORECASE,
        )
        index, count = pattern.subn(
            lambda m: m.group(1) + renamed + "?v=" + VERSION + m.group(2),
            index,
        )
        if count != 1:
            raise RuntimeError(f"Expected exactly one include of {original}, found {count}")
        print(f"{original} -> {renamed}")

    if "agenda-especiales-20261126-v2" not in index:
        raise RuntimeError("No versioned resources referenced")
    (dest / "index.php").write_text(index, encoding="utf-8")
    with (dest / "manifest.sha256").open("w", encoding="utf-8") as output:
        for path in sorted(dest.iterdir()):
            if path.name == "manifest.sha256": continue
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            output.write(f"{digest}  {path.name}\n")
    print("Prepared index.php and versioned assets with SHA-256 manifest.")

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("input", type=Path)
    p.add_argument("output", type=Path)
    a = p.parse_args()
    build(a.input, a.output)
